-- ============================================================
-- fuente_5x7.vhd
-- Fuente de 5x7 pixeles de la interfaz VGA (vga_ui).
--
-- Cada caracter tiene un codigo de 6 bits:
--   0      espacio
--   1-26   A-Z
--   27-36  0-9
--   37-53  % : - / # + . > < ( ) [ ] = ! * ,
--   63     bloque lleno
-- Un caracter son 7 filas de 5 bits; el bit 4 es la columna de la
-- izquierda. La fila 7 (y cualquier codigo sin dibujo) sale vacia.
--
-- txt() y cod_car() convierten texto a codigos. vga_ui solo las
-- usa con constantes, asi que se evaluan al elaborar y en hardware
-- solo queda la ROM de la fuente (fila_fuente). El testbench usa
-- las mismas funciones para revisar lo que sale en pantalla.
-- ============================================================
library ieee;
use ieee.std_logic_1164.all;

package fuente_5x7 is

    subtype t_cod is natural range 0 to 63;
    type t_texto is array (natural range <>) of t_cod;

    constant CH_ESP    : t_cod := 0;
    constant CH_A      : t_cod := 1;
    constant CH_0      : t_cod := 27;
    constant CH_BLOQUE : t_cod := 63;

    -- Codigo de un caracter (los que no hay salen como espacio)
    function cod_car (c : character) return t_cod;

    -- Codigos de un texto, del primer caracter al ultimo (indice 0)
    function txt (s : string) return t_texto;

    -- Fila f (0 arriba) del caracter de codigo c
    function fila_fuente (c : t_cod; f : natural range 0 to 7) return std_logic_vector;

end package fuente_5x7;

