    function cod_car (c : character) return t_cod is
    begin
        case c is
            when 'A' to 'Z' => return character'pos(c) - character'pos('A') + 1;
            when '0' to '9' => return character'pos(c) - character'pos('0') + 27;
            when '%' => return 37;
            when ':' => return 38;
            when '-' => return 39;
            when '/' => return 40;
            when '#' => return 41;
            when '+' => return 42;
            when '.' => return 43;
            when '>' => return 44;
            when '<' => return 45;
            when '(' => return 46;
            when ')' => return 47;
            when '[' => return 48;
            when ']' => return 49;
            when '=' => return 50;
            when '!' => return 51;
            when '*' => return 52;
            when ',' => return 53;
            when others => return 0;
        end case;
    end function;

    function txt (s : string) return t_texto is
        variable r : t_texto(0 to s'length - 1);
    begin
        for i in r'range loop
            r(i) := cod_car(s(s'low + i));
        end loop;
        return r;
    end function;

    function fila_fuente (c : t_cod; f : natural range 0 to 7) return std_logic_vector is
    begin
        if f > 6 then
            return "00000";
        end if;
        return FUENTE(c)(f);
    end function;

